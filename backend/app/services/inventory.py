import re
from datetime import UTC, datetime
from typing import Any

from app.repositories.inventory import ComputerRepository
from app.schemas.scanner import ScannerPayload


class InventoryService:
    def __init__(self, repository: ComputerRepository):
        """Initializes the inventory service with its required repository.

        Args:
            repository (ComputerRepository): The repository for computer database operations.
        """
        self.repository = repository

    @staticmethod
    def parse_powershell_date(date_str: str | None) -> datetime | None:
        """Converts a PowerShell specific date string format into a Python datetime object.

        Args:
            date_str (str | None): The date string generated by PowerShell (e.g., '/Date(1743786151000)/').

        Returns:
            datetime | None: A UTC datetime object representing the extracted timestamp, or None if the input is invalid or missing.
        """
        if not date_str:
            return None
        match = re.search(r'\d+', date_str)
        if match:
            timestamp_ms = int(match.group())
            return datetime.fromtimestamp(timestamp_ms / 1000.0, tz=UTC)
        return None

    @staticmethod
    def ensure_list(item: Any) -> list:
        """Ensures that the provided item is consistently returned as a list.

        Args:
            item (Any): A single object, a list of objects, or None received from the JSON payload.

        Returns:
            list: An empty list if the item is None, the item itself if it is already a list, or a new list containing the single item.
        """
        if item is None:
            return []
        if not isinstance(item, list):
            return [item]
        return item
    @staticmethod
    def clean_null_chars(text: Any) -> Any:
        """Removes NUL (0x00) characters from strings to prevent database ValueError."""
        if isinstance(text, str):
            return text.replace('\x00', '').strip()
        return text

    async def process_inventory_payload(self, payload: ScannerPayload) -> tuple[str, int]:
        """Normalizes the scanner payload and upserts it. Returns (serial_num, computer_id)."""
        computer_data = {
            "serial_num": payload.system.serial_num,
            "hostname": payload.system.hostname,
            "manufacturer": payload.system.manufacturer,
            "model": payload.system.model,
            "equipment_type": payload.system.equipment_type,
            "bios_version": payload.system.bios_version,
            "cpu": payload.system.cpu,
            "ram_gb": payload.system.ram_gb,
            "operating_system": payload.system.operating_system,
            "os_installation_date": self.parse_powershell_date(payload.system.os_installation_date),
            "activity_time": payload.system.activity_time,
            "last_user": payload.system.last_user,
            "battery_health": payload.system.battery_health,
            "antivirus": payload.security.antivirus,
            "local_admins": payload.security.local_admins,
            "reboot_pending": payload.security.reboot_pending,
            "last_verification": payload.verification_date,
        }

        relations = {
            "disks": [{"drive": d.drive, "size_gb": d.size_gb, "free_gb": d.free_gb} for d in self.ensure_list(payload.disks)],
            "monitors": [{"manufacturer": self.clean_null_chars(m.manufacturer), "model": self.clean_null_chars(m.model), "serial_num": self.clean_null_chars(m.serial_num)} for m in self.ensure_list(payload.monitors)],
            "networks": [{"adapter_name": n.adapter_name, "mac_address": n.mac_address, "ip_address": n.ip_address} for n in self.ensure_list(payload.networks)],
            "softwares": [{"software_name": s.software_name, "version": s.version} for s in self.ensure_list(payload.softwares)]
        }

        computer_id = await self.repository.upsert_inventory(computer_data, relations)

        return payload.system.serial_num, computer_id